#!/usr/bin/env python3
"""Generate the victory lyric sheets: docs/VICTORY_LYRICS.md + CSV exports.

Columns, one row per line (lyrics sheet) and one row per sung syllable
(chorus sheet). IPA comes from the same Piper voice the singer uses.

    python tools/lyrics_doc.py
"""
import csv
import json
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
DOC = ROOT / "docs" / "VICTORY_LYRICS.md"
CSV_LINES = ROOT / "docs" / "victory_lines.csv"
CSV_CHORUS = ROOT / "docs" / "victory_chorus.csv"
HULA = ROOT / "godot" / "hula"

sys.path.insert(0, str(TOOLS))
import piper_sing as ps  # noqa: E402

NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def nn(m):
    return f"{NAMES[int(m) % 12]}{int(m) // 12 - 1}"


def load():
    v = json.loads((HULA / "data" / "data_victory.json").read_text(encoding="utf-8"))
    lyr = json.loads((HULA / "data" / "data_lyrics.json").read_text(encoding="utf-8"))["victory_vocals"]
    vox = json.loads((HULA / "data" / "data_vox.json").read_text(encoding="utf-8"))
    return v, lyr, vox


def row(v, section, bar):
    for b in v:
        if b[6] == section and int(b[7]) == bar:
            return b
    return None


def notes_for(v, section, bars):
    out = []
    for i, bar in enumerate(bars):
        b = row(v, section, bar)
        if not b:
            continue
        for s, m in enumerate(b[3]):
            if int(m) > 0:
                out.append((i * 16 + s, int(m)))
    return out


def words_of(text):
    return re.findall(r"[A-Za-z']+", text)


def ipa_of(text, voice, cache):
    out = []
    for w in words_of(text):
        key = w.lower()
        if key not in cache:
            chunks = voice.phonemize(w)
            toks = [t for sent in chunks for t in sent if t.strip() and t not in ",.!?;:"]
            cache[key] = "".join(toks)
        out.append(cache[key])
    return out


def spec():
    return [
        ("A", "v-A", [("A0", 0), ("A2", 2), ("A4", 4), ("A6", 6)], 1),
        ("B", "v-B", [("B0", 0), ("B1", 2), ("B2", 4), ("B3", 6)], 2),
        ("C", "v-C", [("C0", 0), ("C2", 2), ("C4", 4), ("C6", 6)], 1),
        ("tag", "v-tag", [("tag0", 0), ("tag1", 1), ("tag2", 2), ("tag3", 3)], 1),
        ("F", "v-F", [("F0", 0), ("F1", 1), ("F2", 2), ("F3", 3)], 1),
    ]


def main():
    v, lyr, vox = load()
    from piper import PiperVoice
    voice = PiperVoice.load(str(TOOLS / "models" / "en_US-ryan-high.onnx"),
                            config_path=str(TOOLS / "models" / "en_US-ryan-high.onnx.json"),
                            use_cuda=False)
    cache = {}
    lines = []          # dict per clip
    chorus = []         # dict per sung syllable

    for group, sec_name, entries, span in spec():
        for cid, start in entries:
            clip = vox.get(cid, [cid])[0]
            text = lyr.get(clip)
            if not text:
                continue
            bars = list(range(start, start + span))
            words = words_of(text)
            ipa = ipa_of(text, voice, cache)
            bars_s = f"{bars[0]}–{bars[-1]}" if span > 1 else str(bars[0])
            if group == "B":
                mel = []
                for bar in bars:
                    mel += [int(x) for x in row(v, "v-B", bar)[3]]
                pitch, cur = [], 0
                for m in mel:
                    if m > 0:
                        cur = m
                    pitch.append(cur)
                k = ps.syllable_count(text)
                nts = [(b * 4, pitch[b * 4]) for b in range(k)]
                for i, (step, m) in enumerate(nts):
                    chorus.append({
                        "line": cid, "bars": bars_s, "beat": i + 1, "step": step,
                        "word": words[i] if i < len(words) else "",
                        "ipa": ipa[i] if i < len(ipa) else "",
                        "note": nn(m), "midi": m,
                    })
                note_s = " ".join(f"{s}:{nn(m)}" for s, m in nts) + " (last held)"
            else:
                nts = notes_for(v, sec_name, bars)
                note_s = " ".join(f"{s}:{nn(m)}" for s, m in nts)
                if len(nts) > 16:
                    note_s += " ..."
            pairs = " · ".join(f"{w} {p}" for w, p in zip(words, ipa))
            lines.append({
                "line": clip, "section": sec_name, "bars": bars_s,
                "syllables": ps.syllable_count(text), "lyric": text,
                "words_ipa": pairs, "notes": note_s,
            })

    # ---- markdown ------------------------------------------------------
    out = []
    add = out.append
    add("# Victory lyrics — spreadsheet view")
    add("")
    add("Generated by `tools/lyrics_doc.py`. Step = sixteenth slot (0.105 s, 16 per bar);")
    add("four steps = one beat. IPA is what the `en_US-ryan-high` voice says, word by word.")
    add("CSV copies: `docs/victory_lines.csv`, `docs/victory_chorus.csv`.")
    add("")
    add("## Lyrics sheet")
    add("")
    add("| Line | Section | Bars | Syll. | Lyric | Words → IPA | Song notes (step:note) |")
    add("|---|---|---|---|---|---|---|")
    for r in lines:
        add(f"| {r['line']} | {r['section']} | {r['bars']} | {r['syllables']} | "
            f"{r['lyric']} | {r['words_ipa']} | {r['notes']} |")
    add("")
    add("## Chorus sheet — one row per syllable")
    add("")
    add("`v-B` is four two-bar lines (bars 0–1, 2–3, 4–5, 6–7). One syllable per beat;")
    add("the last syllable of each line is held to the end of the phrase.")
    add("")
    add("| Line | Bars | Beat | Step | Word | IPA | Note | MIDI |")
    add("|---|---|---|---|---|---|---|---|")
    for r in chorus:
        add(f"| {r['line']} | {r['bars']} | {r['beat']} | {r['step']} | {r['word']} | "
            f"{r['ipa']} | {r['note']} | {r['midi']} |")
    add("")
    add("`B4`–`B7` are the old one-bar chorus clips and are no longer triggered.")
    add("")
    DOC.write_text("\n".join(out), encoding="utf-8")

    # ---- csv (utf-8-sig so Excel reads IPA) ----------------------------
    with CSV_LINES.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=["line", "section", "bars", "syllables",
                                          "lyric", "words_ipa", "notes"])
        w.writeheader()
        w.writerows(lines)
    with CSV_CHORUS.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=["line", "bars", "beat", "step",
                                          "word", "ipa", "note", "midi"])
        w.writeheader()
        w.writerows(chorus)
    print(f"wrote {DOC.relative_to(ROOT)}, {CSV_LINES.relative_to(ROOT)}, {CSV_CHORUS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
