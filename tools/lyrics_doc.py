#!/usr/bin/env python3
"""Generate docs/VICTORY_LYRICS.md: bars, words, syllables, notes and IPA.

Reads data_lyrics.json / data_vox.json / data_victory.json, and asks the same
Piper voice the singer uses how it pronounces each word, so the doc shows the
sound underneath the spelling.

    python tools/lyrics_doc.py            # rewrite docs/VICTORY_LYRICS.md
"""
import json
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
DOC = ROOT / "docs" / "VICTORY_LYRICS.md"
HULA = ROOT / "godot" / "hula"

sys.path.insert(0, str(TOOLS))
import piper_sing as ps  # noqa: E402

NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
KEEP = set("ˈˌːˑ")  # stress and length marks stay in the display


def nn(m):
    return f"{NAMES[int(m) % 12]}{int(m) // 12 - 1}"


def load():
    v = json.loads((HULA / "data" / "data_victory.json").read_text(encoding="utf-8"))
    lyr = json.loads((HULA / "data" / "data_lyrics.json").read_text(encoding="utf-8"))["victory_vocals"]
    vox = json.loads((HULA / "data" / "data_vox.json").read_text(encoding="utf-8"))
    return v, lyr, vox


def row(v, section, bar):
    for b in v:
        if b[6] == section and int(b[7]) == bar:
            return b
    return None


def notes_for(v, section, bars):
    out = []
    for i, bar in enumerate(bars):
        b = row(v, section, bar)
        if not b:
            continue
        for s, m in enumerate(b[3]):
            if int(m) > 0:
                out.append((i * 16 + s, int(m)))
    return out


def words_of(text):
    return re.findall(r"[A-Za-z']+", text)


def ipa_of(text, voice, cache):
    out = []
    for w in words_of(text):
        key = w.lower()
        if key not in cache:
            chunks = voice.phonemize(w)
            toks = []
            for sent in chunks:
                for t in sent:
                    if t.strip() and t not in ",.!?;:":
                        toks.append(t)
            cache[key] = "".join(toks)
        out.append(cache[key])
    return out


def block(words, ipa):
    widths = [max(len(w), len(p)) + 2 for w, p in zip(words, ipa)]
    top = "".join(w.ljust(x) for w, x in zip(words, widths)).rstrip()
    bot = "".join(p.ljust(x) for p, x in zip(ipa, widths)).rstrip()
    return top, bot


def main():
    v, lyr, vox = load()
    from piper import PiperVoice
    voice = PiperVoice.load(str(TOOLS / "models" / "en_US-ryan-high.onnx"),
                            config_path=str(TOOLS / "models" / "en_US-ryan-high.onnx.json"),
                            use_cuda=False)
    cache = {}
    chorus = {}

    spec = [
        ("A", [("A0", 0), ("A2", 2), ("A4", 4), ("A6", 6)], 1),
        ("B", [("B0", 0), ("B1", 2), ("B2", 4), ("B3", 6)], 2),
        ("C", [("C0", 0), ("C2", 2), ("C4", 4), ("C6", 6)], 1),
        ("tag", [("tag0", 0), ("tag1", 1), ("tag2", 2), ("tag3", 3)], 1),
        ("F", [("F0", 0), ("F1", 1), ("F2", 2), ("F3", 3)], 1),
    ]

    out = []
    add = out.append
    add("# Victory lyrics — bars, words, syllables, notes, pronunciation")
    add("")
    add("Generated by `tools/lyrics_doc.py` from `data_lyrics.json`,")
    add("`data_vox.json` and `data_victory.json`. The second line under each lyric")
    add("is what the Piper voice actually says (IPA, per word).")
    add("")
    add("Step = sixteenth-note slot in the victory sequencer (0.105 s, 16 per bar);")
    add("four steps = one beat. Chorus lines are two bars and are sung one syllable")
    add("per beat, so their notes are written at steps 0, 4, 8, ...")
    add("")
    add("## Lines")
    add("")
    add("| Line | Section / bars | Lyric | Syll. | Notes (step:note) |")
    add("|---|---|---|---|---|")
    lines = []
    for group, entries, span in spec:
        for cid, start in entries:
            clip = vox.get(cid, [cid])[0]
            text = lyr.get(clip)
            if not text:
                continue
            bars = list(range(start, start + span))
            if group == "B":
                mel = []
                for bar in bars:
                    mel += [int(x) for x in row(v, "v-B", bar)[3]]
                pitch, cur = [], 0
                for m in mel:
                    if m > 0:
                        cur = m
                    pitch.append(cur)
                k = ps.syllable_count(text)
                nts = [(b * 4, pitch[b * 4]) for b in range(k)]
                note_s = " ".join(f"{s}:{nn(m)}" for s, m in nts) + f" ({k} beats, last held)"
                sec = f"v-B {bars[0]}–{bars[-1]}"
                chorus[cid] = (text, nts)
            else:
                sec_name = "v-tag" if group == "tag" else f"v-{group}"
                nts = notes_for(v, sec_name, bars)
                note_s = " ".join(f"{s}:{nn(m)}" for s, m in nts[:16])
                if len(nts) > 16:
                    note_s += " ..."
                sec = f"{sec_name} {bars[0]}"
            add(f"| {clip} | {sec} | {text} | {ps.syllable_count(text)} | {note_s} |")
            lines.append((clip, sec, text, note_s))

    add("")
    add("## Pronunciation under the words")
    add("")
    for clip, sec, text, note_s in lines:
        add(f"**{clip}** · {sec} · {ps.syllable_count(text)} syll · {note_s}")
        add("")
        add("```")
        top, bot = block(words_of(text), ipa_of(text, voice, cache))
        add(top)
        add(bot)
        add("```")
        add("")

    add("## Chorus on the beat grid")
    add("")
    add("`v-B` is eight bars of four two-bar lines. `sound.gd` plays one clip every")
    add("other bar; each syllable's vowel is anchored to a beat.")
    add("")
    add("| Beat | Step | " + " | ".join(chorus) + " |")
    add("|---|" + "---|" * (len(chorus) + 1))
    for beat in range(8):
        step = beat * 4
        cells = []
        for cid, (_text, nts) in chorus.items():
            d = dict(nts)
            cells.append(nn(d[step]) if step in d else "·")
        add(f"| {beat + 1} | {step} | " + " | ".join(cells) + " |")
    add("")
    add("`B4`–`B7` are the old one-bar chorus clips and are no longer triggered.")
    add("")

    DOC.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
