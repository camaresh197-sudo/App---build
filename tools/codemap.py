#!/usr/bin/env python3
"""Generate docs/CODEMAP.md: a compact line-number index of the GDScript files.

The scripts are the expensive part of this repo (hero3d.gd alone is ~26k tokens),
so agents should jump to a line slice instead of reading a whole file. This tool
lists section headers, function signatures and top-level constant/variable names
with line numbers, then prints the token estimate of each full file.

Usage:
    python3 tools/codemap.py [--out docs/CODEMAP.md]
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "godot", "hula", "scripts")

FUNC = re.compile(r"^(static\s+func|func)\s+(.+)$")
DECL = re.compile(r"^const\s+([A-Za-z_][A-Za-z0-9_]*)")
SECTION = re.compile(r"^#\s*-{3,}\s*(.+?)\s*-{3,}\s*$")


def index_file(text):
    lines = text.splitlines()
    rows = []
    for i, line in enumerate(lines, 1):
        m = SECTION.match(line)
        if m:
            rows.append((i, "-- " + m.group(1) + " --"))
            continue
        m = FUNC.match(line)
        if m:
            sig = m.group(2).strip()
            if sig.endswith(":"):
                sig = sig[:-1]
            if len(sig) > 96:
                sig = sig[:93] + "..."
            rows.append((i, m.group(1) + " " + sig))
            continue
        m = DECL.match(line)
        if m:
            rows.append((i, "const " + m.group(1)))
    return len(lines), rows


def main():
    out = os.path.join(ROOT, "docs", "CODEMAP.md")
    args = sys.argv[1:]
    if "--out" in args and args.index("--out") + 1 < len(args):
        out = args[args.index("--out") + 1]

    files = []
    for name in sorted(os.listdir(SCRIPTS)):
        if not name.endswith(".gd"):
            continue
        with open(os.path.join(SCRIPTS, name), encoding="utf-8") as f:
            text = f.read()
        n, rows = index_file(text)
        files.append((name, n, len(text) // 4, rows))

    parts = [
        "# CODEMAP - generated by `tools/codemap.py`, do not hand-edit",
        "",
        "Jump tables for the GDScript. Read a slice (`offset`/`limit`) instead of a whole",
        "file. Regenerate with `python3 tools/codemap.py` after moving functions.",
        "Constants are listed by name only: grep `^const` for values, `^var` for state.",
        "",
        "| File | Lines | ~Tokens |",
        "|---|---:|---:|",
    ]
    for name, n, tok, _ in files:
        parts.append("| `scripts/%s` | %d | %d |" % (name, n, tok))
    parts.append("")

    for name, n, tok, rows in files:
        parts.append("## `scripts/%s`" % name)
        parts.append("")
        parts.append("```text")
        for line_no, label in rows:
            parts.append("%4d  %s" % (line_no, label))
        parts.append("```")
        parts.append("")

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts))
    print("wrote %s (%d chars, ~%d tokens)" % (out, os.path.getsize(out), os.path.getsize(out) // 4))
    return 0


if __name__ == "__main__":
    sys.exit(main())
